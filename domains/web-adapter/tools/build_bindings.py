#!/usr/bin/env python3
"""Build the web-adapter bindings from skills/binding-source.md.

  build_bindings.py [--shape <shape-folder>] [--out <skills-folder>]

The six rules are read verbatim from <shape>/README.md (the "## Six rules" section). By default the
shape is two folders above this domain, where it sits once installed (<shape>/domains/web-adapter).
A platform declaring "rules: safe" uses the platform-safe wording in the source instead.
Fails loudly if the README has no six numbered rules. Exit 0 built, 1 failed.
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOMAIN = os.path.dirname(HERE)
PART = re.compile(r"<!-- (platform|part|surface): ([\w-]+)((?: \| [^>]*?)?) -->\n(.*?)<!-- end -->", re.S)
NOTE = "<!-- Generated by tools/build_bindings.py from skills/binding-source.md (rules: {mode}). Do not edit. -->"


def shape_rules(shape):
    path = os.path.join(shape, "README.md")
    if not os.path.exists(path):
        raise SystemExit(f"FAIL: no README.md in {shape}; pass --shape")
    text = open(path, encoding="utf-8").read()
    m = re.search(r"^## Six rules\n(.*?)(?=^## )", text, re.S | re.M)
    rules = re.findall(r"^[1-6]\. .+$", m.group(1), re.M) if m else []
    if len(rules) != 6:
        raise SystemExit(f"FAIL: {path} has no '## Six rules' section with six numbered rules")
    return "\n".join(rules)


def parse(source):
    parts = {"platform": {}, "part": {}, "surface": {}}
    for kind, name, attrs, body in PART.findall(source):
        meta = dict(a.split(": ", 1) for a in attrs.strip(" |").split(" | ") if ": " in a)
        parts[kind][name] = (meta, body)
    return parts


def build(shape, out):
    source = open(os.path.join(DOMAIN, "skills", "binding-source.md"), encoding="utf-8").read()
    parts = parse(source)
    verbatim = shape_rules(shape)
    common = parts["part"]["common"][1]
    written = []
    for name, (meta, head) in parts["platform"].items():
        mode = meta.get("rules", "verbatim")
        rules = parts["part"]["safe-rules"][1].strip() if mode == "safe" else verbatim
        surface = parts["surface"][name][1].strip()
        body = common.replace("{{RULES}}", rules).replace("{{SURFACE}}", surface)
        head = head.strip("\n")
        if head.startswith("---\n"):
            fm_end = head.index("\n---\n", 4) + 5
            text = head[:fm_end] + NOTE.format(mode=mode) + "\n\n" + head[fm_end:].lstrip("\n")
        else:
            text = NOTE.format(mode=mode) + "\n\n" + head
        text = text.rstrip("\n") + "\n\n" + body.strip("\n") + "\n"
        path = os.path.join(out, meta["file"])
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        written.append((path, len(text)))
    return written


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shape", default=os.path.join(DOMAIN, "..", ".."))
    ap.add_argument("--out", default=os.path.join(DOMAIN, "skills"))
    a = ap.parse_args()
    for path, n in build(a.shape, a.out):
        print(f"built {os.path.relpath(path, a.out)} ({n} characters)")


if __name__ == "__main__":
    main()
